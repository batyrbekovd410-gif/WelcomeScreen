def adventure(cat_name):

    print("\n🌳 НАЧАЛО ПРИКЛЮЧЕНИЯ")
    print(cat_name, "вышел из дома.")

    print(cat_name, "увидел дерево.")
    print(cat_name, "подошёл к дереву.")
    print(cat_name, "решил залезть на дерево.")

    for level in range(1, 6):
        print("Кот поднялся на уровень", level)

    print(cat_name, "сидит на дереве.")
    print("Ветер дует...")
    print("Птички поют...")
    print(cat_name, "смотрит на город.")

    print("\n🌙 Приключение закончилось.")
    print(cat_name, "возвращается домой.")


