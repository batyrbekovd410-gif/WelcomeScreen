    if value >= 80:
        print("\n😺 Кот очень счастлив!")

    elif value >= 50:
        print("\n🙂 Кот чувствует себя нормально.")

    elif value >= 20:
        print("\n😿 Кот немного грустный.")

    else:
        print("\n😭 Кот очень грустный.")


